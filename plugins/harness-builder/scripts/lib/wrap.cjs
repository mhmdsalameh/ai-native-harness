'use strict';
// `claude plugin eval` loads only plugins. wrap() copies a project .claude/ or ~/.claude harness into an
// eval-ready plugin; variant() copies a suite with always-loaded text set as append_system_prompt.

const fs = require('fs');
const path = require('path');
const { detectLayout, collectImports } = require('./inventory.cjs');
const { readDoc, addBlockField } = require('./fm.cjs');
const { findCases } = require('./ledger.cjs');

const WRAP_MARKER = 'WRAP-REPORT.md';
const VARIANT_MARKER = 'VARIANT.md';
const RESERVED_SKILL_DIRS = new Set(['synced', 'anthropic-skills']);

const isDir = (p) => { try { return fs.statSync(p).isDirectory(); } catch { return false; } };
const escapeRe = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

function copyDir(src, dst, skip = () => false) {
  fs.mkdirSync(dst, { recursive: true });
  for (const ent of fs.readdirSync(src, { withFileTypes: true })) {
    if (skip(ent.name, path.join(src, ent.name))) continue;
    const s = path.join(src, ent.name);
    const d = path.join(dst, ent.name);
    if (ent.isDirectory()) copyDir(s, d, skip);
    else if (ent.isFile()) fs.copyFileSync(s, d);
  }
}

// Only a folder this tool generated (it holds the marker) may be replaced.
function prepareOut(out, marker) {
  if (fs.existsSync(out)) {
    const entries = fs.readdirSync(out);
    if (entries.length && !entries.includes(marker)) throw new Error(`refusing to overwrite ${out}: not empty and not generated by hb (no ${marker})`);
    fs.rmSync(out, { recursive: true, force: true });
  }
  fs.mkdirSync(out, { recursive: true });
}

function slug(s) {
  return s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '') || 'harness';
}

// Every spelling of the harness folder a hook command may use: the absolute path (either slash), and
// each env var that points at its parent in bash, PowerShell and cmd syntax (quoted or not).
function harnessPrefixes(L) {
  const vars = L.kind === 'user' ? ['HOME', 'USERPROFILE'] : ['CLAUDE_PROJECT_DIR'];
  const forms = (v) => [`$${v}`, `\${${v}}`, `"$${v}"`, `"\${${v}}"`, `$env:${v}`, `%${v}%`];
  const alts = [L.compDir, L.compDir.replace(/\\/g, '/')].map(escapeRe);
  const parents = vars.flatMap(forms);
  if (L.kind === 'user') parents.push('~');
  alts.push('(?:' + parents.sort((a, b) => b.length - a.length).map(escapeRe).join('|') + ')[\\\\/]\\.claude');
  return new RegExp('(?:' + alts.join('|') + ')[\\\\/]', 'gi');
}

function rewriteHooks(hooks, re, notes) {
  const walk = (v) => {
    if (Array.isArray(v)) return v.map(walk);
    if (v && typeof v === 'object') {
      const o = {};
      for (const [k, x] of Object.entries(v)) {
        if (k === 'command' && typeof x === 'string') {
          o[k] = x.replace(re, '${CLAUDE_PLUGIN_ROOT}/');
          if (/CLAUDE_PROJECT_DIR/.test(o[k])) notes.push(`hook command still uses CLAUDE_PROJECT_DIR (points at the empty eval workspace): ${o[k]}`);
          else if (/[\\/]\.claude[\\/]/.test(o[k])) notes.push(`hook command still points into a .claude folder outside the plugin: ${o[k]}`);
        } else o[k] = walk(x);
      }
      return o;
    }
    return v;
  };
  return walk(hooks);
}

function wrap(src, out, opts = {}) {
  const L = detectLayout(src, opts);
  if (L.kind === 'plugin') throw new Error(`${L.root} is already a plugin; run claude plugin eval on it directly`);
  const outAbs = path.resolve(out);
  prepareOut(outAbs, WRAP_MARKER);
  const name = opts.name ? slug(opts.name) : 'wrapped-' + slug(path.basename(L.kind === 'user' ? path.dirname(L.compDir) : L.root));
  const carried = [];
  const notCarried = [];

  for (const dir of ['skills', 'agents', 'commands', 'hooks', 'scripts']) {
    const s = path.join(L.compDir, dir);
    if (!isDir(s)) continue;
    const skipped = [];
    copyDir(s, path.join(outAbs, dir), (n, p) => {
      if (n.startsWith('.')) return true;
      if (dir === 'skills' && path.dirname(p) === s && RESERVED_SKILL_DIRS.has(n)) { skipped.push(n); return true; }
      return false;
    });
    carried.push(`${dir}/`);
    for (const n of skipped) notCarried.push(`skills/${n}/ (reserved folder name; first-party skills, not part of this harness)`);
  }

  for (const f of fs.existsSync(path.join(outAbs, 'agents')) ? fs.readdirSync(path.join(outAbs, 'agents')) : []) {
    if (!f.endsWith('.md')) continue;
    const ignored = ['hooks', 'mcpServers', 'permissionMode'].filter((k) => k in readDoc(path.join(outAbs, 'agents', f)).data);
    if (ignored.length) notCarried.push(`agents/${f}: ${ignored.join(', ')} (plugin agents ignore these keys)`);
  }

  const settings = L.settings && fs.existsSync(L.settings) ? JSON.parse(fs.readFileSync(L.settings, 'utf8')) : {};
  if (settings.hooks) {
    const notes = [];
    const hooks = rewriteHooks(settings.hooks, harnessPrefixes(L), notes);
    fs.mkdirSync(path.join(outAbs, 'hooks'), { recursive: true });
    fs.writeFileSync(path.join(outAbs, 'hooks', 'hooks.json'), JSON.stringify({ hooks }, null, 2) + '\n');
    carried.push('settings.json hooks -> hooks/hooks.json (paths rewritten to ${CLAUDE_PLUGIN_ROOT})');
    notCarried.push(...notes);
  }
  const otherSettings = Object.keys(settings).filter((k) => k !== 'hooks' && k !== '$schema');
  if (otherSettings.length) notCarried.push(`settings.json keys: ${otherSettings.join(', ')} (plugins cannot set these; eval runs use defaults)`);

  if (L.mcpFile && fs.existsSync(L.mcpFile)) {
    fs.copyFileSync(L.mcpFile, path.join(outAbs, '.mcp.json'));
    carried.push('.mcp.json (eval runs answer MCP tools from evals/mocks/ unless --mocks off)');
  }

  const seen = new Set();
  const parts = [];
  for (const f of L.claudeMds) for (const m of collectImports(f, path.resolve(opts.home || require('os').homedir()), seen)) parts.push(m);
  const rulesDir = path.join(L.compDir, 'rules');
  const scoped = [];
  if (isDir(rulesDir)) {
    const walk = (d) => {
      for (const ent of fs.readdirSync(d, { withFileTypes: true })) {
        const p = path.join(d, ent.name);
        if (ent.isDirectory()) walk(p);
        else if (ent.name.endsWith('.md') && !seen.has(p.toLowerCase())) {
          const doc = readDoc(p);
          if (doc.data.paths) scoped.push(path.relative(L.compDir, p));
          else { seen.add(p.toLowerCase()); parts.push({ file: p, text: doc.text }); }
        }
      }
    };
    walk(rulesDir);
  }
  for (const s of scoped) notCarried.push(`${s} (path-scoped rule; loads only when matching files are read)`);
  let contextFile = null;
  let contextTokens = 0;
  if (parts.length) {
    const text = parts.map((p) => `<!-- from: ${p.file} -->\n${p.text.trim()}\n`).join('\n');
    contextFile = path.join(outAbs, 'context.md');
    fs.writeFileSync(contextFile, text);
    contextTokens = Math.ceil(text.length / 4);
    carried.push(`CLAUDE.md + imports + unscoped rules -> context.md (~${contextTokens} tokens); use hb variant to test it`);
  }

  if (opts.evals) {
    copyDir(path.resolve(opts.evals), path.join(outAbs, 'evals'), (n) => n === 'results');
    carried.push(`eval suite from ${opts.evals} -> evals/`);
  }

  fs.mkdirSync(path.join(outAbs, '.claude-plugin'), { recursive: true });
  fs.writeFileSync(path.join(outAbs, '.claude-plugin', 'plugin.json'), JSON.stringify({
    name, version: '0.0.0', description: `Eval copy of the ${L.kind} harness at ${L.root}, generated by hb wrap.`,
  }, null, 2) + '\n');

  const report = [`# Wrapped harness: ${name}`, '', `Source: ${L.root} (${L.kind})`, `Generated by \`hb wrap\`. Re-running wrap replaces this folder.`, '',
    '## Carried', '', ...carried.map((c) => `- ${c}`), '', '## Not carried', '', ...(notCarried.length ? notCarried.map((c) => `- ${c}`) : ['- nothing']), '',
    '## Limits', '', '- context.md is tested through `append_system_prompt`, which is appended to the system prompt. Real CLAUDE.md text arrives as context at session start, so treat the result as an approximation.', ''].join('\n');
  fs.writeFileSync(path.join(outAbs, WRAP_MARKER), report);
  return { out: outAbs, name, kind: L.kind, carried, notCarried, contextFile, contextTokens };
}

function checkEvalDirName(d) {
  if (!/^[\w.-]+(\/[\w.-]+)*$/.test(d) || d.split('/').includes('..')) throw new Error(`eval dir must be a relative path of plain folder names (no .. or absolute): ${d}`);
}

function variant(pluginDir, from, to, appendFile) {
  checkEvalDirName(from);
  checkEvalDirName(to);
  if (from === to || to.startsWith(from + '/') || from.startsWith(to + '/')) throw new Error('--from and --to must be separate folders');
  const root = path.resolve(pluginDir);
  const fromAbs = path.join(root, from);
  const toAbs = path.join(root, to);
  if (!isDir(fromAbs)) throw new Error(`no eval suite at ${fromAbs}`);
  const context = fs.readFileSync(appendFile, 'utf8');
  prepareOut(toAbs, VARIANT_MARKER);
  copyDir(fromAbs, toAbs, (n) => n === 'results');
  const patched = [];
  const skipped = [];
  for (const c of findCases(toAbs)) {
    const pm = path.join(c, 'prompt.md');
    const rel = path.relative(toAbs, c);
    if (!fs.existsSync(pm)) { skipped.push(`${rel}: case.yaml only; add execution.append_system_prompt by hand`); continue; }
    const doc = readDoc(pm);
    if ('append_system_prompt' in doc.data) { skipped.push(`${rel}: already sets append_system_prompt`); continue; }
    fs.writeFileSync(pm, addBlockField(doc.text, 'append_system_prompt', context));
    patched.push(rel);
  }
  fs.writeFileSync(path.join(toAbs, VARIANT_MARKER), `# Variant suite\n\nCopy of \`${from}\` with append_system_prompt from ${path.resolve(appendFile)}.\nGenerated by \`hb variant\`; re-running replaces this folder.\n`);
  return { suite: toAbs, patched, skipped };
}

module.exports = { wrap, variant, copyDir, WRAP_MARKER, VARIANT_MARKER };
